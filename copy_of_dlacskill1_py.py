"""Task 13 – Vehicle Speed Estimation

Run the speed estimation code
"""

import cv2
import math

# Approximate calibration value
PIXELS_PER_METER = 10

# Read video information
cap = cv2.VideoCapture(video_path)
fps = cap.get(cv2.CAP_PROP_FPS)
width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
cap.release()

# Create output video
output_path = "visionport_speed_estimation.mp4"
writer = cv2.VideoWriter(
    output_path,
    cv2.VideoWriter_fourcc(*"mp4v"),
    fps,
    (width, height)
)

previous_positions = {}
frame_number = 0

# Track vehicles
speed_results = model.track(
    source=video_path,
    classes=[2, 3, 5, 7],
    conf=0.4,
    tracker="bytetrack.yaml",
    persist=True,
    stream=True
)

for result in speed_results:

    frame = result.orig_img.copy()

    if result.boxes.id is not None:

        boxes = result.boxes.xyxy.cpu().numpy()
        ids = result.boxes.id.int().cpu().tolist()

        for box, track_id in zip(boxes, ids):

            x1, y1, x2, y2 = map(int, box)

            center_x = (x1 + x2) // 2
            center_y = (y1 + y2) // 2

            speed = 0.0

            if track_id in previous_positions:
                old_x, old_y, old_frame = previous_positions[track_id]

                distance_pixels = math.sqrt(
                    (center_x - old_x)**2 +
                    (center_y - old_y)**2
                )

                time_difference = (frame_number - old_frame) / fps

                if time_difference > 0:
                    speed = (
                        distance_pixels /
                        PIXELS_PER_METER /
                        time_difference
                    ) * 3.6

            previous_positions[track_id] = (
                center_x, center_y, frame_number
            )

            label = f"ID {track_id} | {speed:.1f} km/h"

            cv2.rectangle(
                frame, (x1, y1), (x2, y2),
                (0, 255, 0), 2
            )

            cv2.putText(
                frame, label, (x1, max(y1 - 10, 20)),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.6, (0, 255, 255), 2
            )

    writer.write(frame)
    frame_number += 1

writer.release()

print("Vehicle speed estimation completed!")
print("Output:", output_path)

