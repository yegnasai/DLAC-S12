"""Task 15 – Vehicle Waiting-Time Estimation"""

import math
from collections import defaultdict

cap = cv2.VideoCapture(video_path)
fps = cap.get(cv2.CAP_PROP_FPS) or 30

previous = {}
waiting_start = {}
waiting_times = defaultdict(float)

frame_no = 0
WAIT_THRESHOLD = 8  # pixels

while True:
    ret, frame = cap.read()
    if not ret:
        break

    output = model.track(
        frame,
        persist=True,
        tracker="bytetrack.yaml",
        classes=[2, 3, 5, 7],
        conf=0.4,
        verbose=False
    )[0]

    if output.boxes.id is not None:
        boxes = output.boxes.xyxy.cpu().numpy()
        ids = output.boxes.id.int().cpu().tolist()

        for box, track_id in zip(boxes, ids):
            x1, y1, x2, y2 = map(int, box)
            cx, cy = (x1+x2)//2, (y1+y2)//2

            if track_id in previous:
                px, py = previous[track_id]
                movement = math.hypot(cx-px, cy-py)

                if movement < WAIT_THRESHOLD:
                    waiting_start.setdefault(track_id, frame_no)
                else:
                    waiting_start.pop(track_id, None)

            previous[track_id] = (cx, cy)

            if track_id in waiting_start:
                waiting_times[track_id] = (
                    frame_no - waiting_start[track_id]
                ) / fps

            cv2.putText(
                frame,
                f"ID {track_id}",
                (x1, y1-10),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.6, (0,255,0), 2
            )

    frame_no += 1

cap.release()

print("VEHICLE WAITING TIME REPORT")
for track_id, seconds in waiting_times.items():
    print("Vehicle ID:", track_id,
          "| Waiting Time:", round(seconds, 2), "seconds")

