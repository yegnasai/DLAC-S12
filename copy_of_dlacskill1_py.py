"""Task 20 – Triple-Riding Detection"""

cap = cv2.VideoCapture(video_path)

triple_riding_alerts = 0
frame_number = 0

while True:
    ret, frame = cap.read()
    if not ret:
        break

    # YOLO class 0 = person
    # YOLO class 3 = motorcycle
    result = model.predict(
        frame,
        classes=[0, 3],
        conf=0.35,
        verbose=False
    )[0]

    persons = []
    motorcycles = []

    for box in result.boxes:
        class_id = int(box.cls[0])
        x1, y1, x2, y2 = map(int, box.xyxy[0])

        if class_id == 0:
            persons.append((x1, y1, x2, y2))

        elif class_id == 3:
            motorcycles.append((x1, y1, x2, y2))

    for bike in motorcycles:
        bx1, by1, bx2, by2 = bike

        # Expand motorcycle box to include riders
        rx1 = max(0, bx1 - 20)
        ry1 = max(0, by1 - 3 * (by2 - by1))
        rx2 = min(frame.shape[1], bx2 + 20)
        ry2 = min(frame.shape[0], by2 + 20)

        rider_count = 0

        for person in persons:
            px1, py1, px2, py2 = person

            pcx = (px1 + px2) // 2
            pcy = (py1 + py2) // 2

            if rx1 <= pcx <= rx2 and ry1 <= pcy <= ry2:
                rider_count += 1

        cv2.rectangle(
            frame, (bx1, by1), (bx2, by2),
            (0, 255, 0), 2
        )

        if rider_count > 2:
            triple_riding_alerts += 1

            cv2.putText(
                frame, "TRIPLE RIDING ALERT!",
                (bx1, max(25, by1-10)),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.6, (0, 0, 255), 2
            )

            print("Triple riding suspected!")

    frame_number += 1

cap.release()

print("Triple Riding Analysis Completed!")
print("Alert frames:", triple_riding_alerts)