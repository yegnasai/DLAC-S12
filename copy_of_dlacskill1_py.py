    angle = math.degrees(math.atan2(dy, dx))

    if -135 <= angle <= -45:
        turn = "LEFT / UPWARD MOVEMENT"
    elif 45 <= angle <= 135:
        turn = "RIGHT / DOWNWARD MOVEMENT"
    else:
        turn = "STRAIGHT / HORIZONTAL MOVEMENT"

